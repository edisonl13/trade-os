/**
 * Get a translated string for the given locale.
 * Falls back to en-US if key is missing.
 */
export function t(locale: Locale, key: string, ...args: string[]): string {
  // Try the requested locale, fall back to en-US
  const dict = dictionaries[locale] ?? dictionaries["en-US"];
  let value = dict[key];
  if (value === undefined) {
    value = dictionaries["en-US"][key];
  }
  if (value === undefined) return key;

  if (typeof value === "function") {
    return value(...args);
  }

  // Replace {0}, {1}, etc. with args
  if (args.length > 0) {
    return value.replace(/\{(\d+)\}/g, (_, idx) => args[parseInt(idx)] ?? "");
  }

  return value;
}

/**
 * Detect browser locale, defaulting to en-US.
 */
export function detectLocale(): Locale {
  if (typeof navigator === "undefined") return "en-US";
  const lang = navigator.language;
  if (lang.startsWith("zh")) {
    if (lang === "zh-TW" || lang === "zh-HK") return "zh-TW";
    return "zh-CN";
  }
  if (lang.startsWith("ja")) return "ja-JP";
  if (lang.startsWith("en")) {
    if (lang === "en-GB") return "en-GB";
    return "en-US";
  }
  return "en-US";
}
